-- Additive schema for official maximum points by class, subject, year and semester.
create table if not exists public.subject_assessment_scales (
  id bigint generated by default as identity primary key,
  class_id bigint not null references public.school_classes(id) on delete cascade,
  subject_id bigint not null references public.subjects(id) on delete cascade,
  school_year text not null default '2026-2027',
  semester_1_max numeric(8,2),
  semester_2_max numeric(8,2),
  annual_max numeric(8,2) generated always as (coalesce(semester_1_max,0) + coalesce(semester_2_max,0)) stored,
  period_maxima jsonb not null default '{}'::jsonb,
  source_reference text not null default 'Bulletin ministériel fourni par l’établissement',
  verification_status text not null default 'à vérifier'
    check (verification_status in ('vérifié','à vérifier','personnalisé')),
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint subject_assessment_scales_unique unique (class_id, subject_id, school_year),
  constraint subject_assessment_scales_nonnegative check (
    (semester_1_max is null or semester_1_max >= 0) and
    (semester_2_max is null or semester_2_max >= 0)
  ),
  constraint subject_assessment_scales_periods_object check (jsonb_typeof(period_maxima) = 'object')
);
create index if not exists subject_assessment_scales_year_class_idx
  on public.subject_assessment_scales (school_year, class_id);
alter table public.subject_assessment_scales enable row level security;
grant select, insert, update, delete on public.subject_assessment_scales to authenticated;
grant usage, select on sequence public.subject_assessment_scales_id_seq to authenticated;
create policy "school_users_read_assessment_scales"
  on public.subject_assessment_scales for select to authenticated
  using (private.is_school_user());
create policy "school_admin_manage_assessment_scales"
  on public.subject_assessment_scales for all to authenticated
  using (private.is_school_admin())
  with check (private.is_school_admin());
