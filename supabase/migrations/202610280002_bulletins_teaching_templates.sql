-- 1) Affectations des titulaires et professeurs aux classes/matières.
CREATE TABLE IF NOT EXISTS public.teaching_assignments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES public.profiles(user_id) ON DELETE CASCADE,
  class_id bigint NOT NULL REFERENCES public.school_classes(id) ON DELETE CASCADE,
  subject_id bigint REFERENCES public.subjects(id) ON DELETE CASCADE,
  assignment_type text NOT NULL CHECK (assignment_type IN ('titulaire','professeur')),
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT teaching_assignment_subject_rule CHECK (
    (assignment_type = 'titulaire' AND subject_id IS NULL)
    OR (assignment_type = 'professeur' AND subject_id IS NOT NULL)
  )
);
CREATE UNIQUE INDEX IF NOT EXISTS teaching_assignments_unique
ON public.teaching_assignments(user_id, class_id, COALESCE(subject_id, 0), assignment_type);
ALTER TABLE public.teaching_assignments ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS teaching_assignments_read_authenticated ON public.teaching_assignments;
CREATE POLICY teaching_assignments_read_authenticated
ON public.teaching_assignments FOR SELECT TO authenticated USING (true);
DROP POLICY IF EXISTS teaching_assignments_admin_all ON public.teaching_assignments;
CREATE POLICY teaching_assignments_admin_all
ON public.teaching_assignments FOR ALL TO authenticated
USING (public.is_school_admin()) WITH CHECK (public.is_school_admin());
DROP POLICY IF EXISTS teaching_assignments_admin_all_restrictive ON public.teaching_assignments;
CREATE POLICY teaching_assignments_admin_all_restrictive
ON public.teaching_assignments AS RESTRICTIVE FOR ALL TO authenticated
USING (public.is_school_admin()) WITH CHECK (public.is_school_admin());

