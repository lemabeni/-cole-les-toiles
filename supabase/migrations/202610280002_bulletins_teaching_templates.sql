ALTER TABLE public.grades ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS school_grade_insert_assigned_staff ON public.grades;
CREATE POLICY school_grade_insert_assigned_staff
ON public.grades FOR INSERT TO authenticated
WITH CHECK (
  public.is_school_admin()
  OR EXISTS (
    SELECT 1
    FROM public.students st
    JOIN public.teaching_assignments ta ON ta.class_id = st.class_id
    WHERE st.id = grades.student_id
      AND st.school_year = grades.school_year
      AND (
        (ta.user_id = auth.uid() AND ta.assignment_type = 'titulaire' AND ta.subject_id IS NULL)
        OR (ta.user_id = auth.uid() AND ta.assignment_type = 'professeur' AND ta.subject_id = grades.subject_id)
      )
  )
);
DROP POLICY IF EXISTS school_grade_update_assigned_staff ON public.grades;
